/**
 * Membuat "translator": objek dengan semua string terjemahan + helper make().
 * make(key, vars) mengganti placeholder {x} dengan nilai dari vars.
 */
export function createTranslator(code) {
  const strings = STRINGS[code] || STRINGS.en;
  const t = { ...strings, code };
  t.make = (key, vars = {}) => {
    let s = strings[key] ?? key;
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  };
  return t;
}
